import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'

const root = process.cwd()
const uiDirectory = join(root, 'src', 'ui')
const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const packageVersions = {
  ...packageJson.dependencies,
  ...packageJson.devDependencies,
}

const packageName = specifier => {
  if (specifier.startsWith('@')) {
    return specifier.split('/').slice(0, 2).join('/')
  }

  return specifier.split('/')[0]
}

const title = name =>
  name
    .split('-')
    .map(part => (part === 'kbd' ? 'Kbd' : part[0].toUpperCase() + part.slice(1)))
    .join(' ')

const categories = {
  'Data display': new Set(['avatar', 'badge', 'bubble', 'chart', 'data-table', 'item', 'kbd', 'marker', 'table', 'typography']),
  'Feedback': new Set(['alert', 'empty', 'message', 'message-scroller', 'progress', 'skeleton', 'sonner', 'spinner', 'toast']),
  'Forms': new Set(['button', 'button-group', 'checkbox', 'combobox', 'field', 'form', 'input', 'input-group', 'input-otp', 'label', 'native-select', 'radio-group', 'select', 'slider', 'switch', 'textarea', 'toggle', 'toggle-group']),
  'Layout': new Set(['aspect-ratio', 'card', 'carousel', 'resizable', 'scroll-area', 'separator', 'sidebar']),
  'Navigation': new Set(['breadcrumb', 'command', 'menubar', 'navigation-menu', 'pagination', 'tabs']),
  'Overlay': new Set(['alert-dialog', 'context-menu', 'dialog', 'direction', 'drawer', 'dropdown-menu', 'hover-card', 'popover', 'sheet', 'tooltip']),
}

const category = name =>
  Object.entries(categories).find(([, names]) => names.has(name))?.[0] ?? 'Other'

const registryAddress = item => `Potti1234/creaseui/${item}`
const libraryItems = {
  '@/lib/utils': 'utils',
  '@/lib/icon': 'icons',
  '@/lib/echarts': 'echarts-adapter',
}
const consumerFrameworkPackages = new Set([
  '@effect/platform-browser',
  '@foldkit/ui',
  'effect',
  'foldkit',
])

const files = readdirSync(uiDirectory)
  .filter(file => file.endsWith('.ts') && file !== 'registry.json')
  .sort()

const items = files.map(file => {
  const name = basename(file, '.ts')
  const source = readFileSync(join(uiDirectory, file), 'utf8')
  const specifiers = Array.from(
    source.matchAll(/from\s+['"]([^'"]+)['"]/g),
    match => match[1],
  )
  const npmPackages = new Set()
  const registryDependencies = new Set([registryAddress('crease-theme')])

  for (const specifier of specifiers) {
    if (libraryItems[specifier] !== undefined) {
      registryDependencies.add(registryAddress(libraryItems[specifier]))
      continue
    }

    if (specifier.startsWith('@/ui/')) {
      registryDependencies.add(registryAddress(specifier.slice('@/ui/'.length)))
      continue
    }

    if (specifier.startsWith('.') || specifier.startsWith('@/')) {
      continue
    }

    const dependency = packageName(specifier)

    if (!consumerFrameworkPackages.has(dependency)) {
      npmPackages.add(dependency)
    }
  }

  const dependencies = Array.from(npmPackages)
    .sort()
    .map(dependency => {
      const version = packageVersions[dependency]
      return version === undefined ? dependency : `${dependency}@${version}`
    })

  return {
    name,
    type: 'registry:ui',
    title: title(name),
    description: `A shadcn-styled ${title(name)} component for Foldkit.`,
    ...(dependencies.length === 0 ? {} : { dependencies }),
    registryDependencies: Array.from(registryDependencies).sort(),
    files: [
      {
        path: file,
        type: 'registry:ui',
        target: `@ui/${file}`,
      },
    ],
  }
})

const registry = {
  $schema: 'https://ui.shadcn.com/schema/registry.json',
  items,
}

writeFileSync(
  join(uiDirectory, 'registry.json'),
  `${JSON.stringify(registry, null, 2)}\n`,
)

const escapeCell = value => value.replaceAll('|', '\\|')
const catalogRows = items.map(item => {
  const source = readFileSync(join(uiDirectory, item.files[0].path), 'utf8')
  const state = /export (?:type|interface) Model\b/.test(source) &&
    /export const update\b/.test(source)
    ? 'Stateful'
    : 'Stateless'
  const packages = item.dependencies ?? []
  const registryItems = item.registryDependencies
    .map(dependency => dependency.split('/').at(-1))
    .filter(dependency => dependency !== 'crease-theme')
  const requirements = [...packages, ...registryItems].join(', ') || 'Theme only'

  return `| ${item.title} | ${category(item.name)} | ${state} | ${escapeCell(requirements)} | \`${registryAddress(item.name)}\` |`
})

writeFileSync(
  join(root, 'docs', 'component-catalog.md'),
  `# Component catalog\n\nThis file is generated by \`npm run registry:generate\`. Every component also installs the Crease theme token contract. “Stateful” means the module owns a Foldkit child model and update function; “Stateless” modules are render helpers or controlled views.\n\n| Component | Category | State | Additional requirements | Registry install name |\n| --- | --- | --- | --- | --- |\n${catalogRows.join('\n')}\n`,
)

console.log(`Generated ${items.length} UI registry items and the component catalog.`)
