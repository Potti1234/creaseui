#!/usr/bin/env node
/* Regenerates public/tutorial-essays.css: the Tailwind utility classes used
   by the vendored tutorial essays in src/docs/tutorial/guide/. The Tailwind
   site emits them itself during its normal build scan; the StyleX and Pleat
   sites have no Tailwind pipeline, so vite.config.ts links this file into
   their index.html. It lives in public/ (not imported) so the build's
   "no Tailwind on the StyleX/Pleat site" bundle check does not see it — that
   check guards against accidental leaks, while this file is intentional.

   The theme wiring (@custom-variant dark, @theme inline) is extracted from
   src/styles.css so the emitted utilities match the Tailwind site's output for
   the same classes. */

import { Scanner } from '@tailwindcss/oxide'
import { compile } from 'tailwindcss'
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const require_ = createRequire(import.meta.url)
const root = path.resolve(import.meta.dirname, '..')
const stylesPath = path.join(root, 'src', 'styles.css')
const outPath = path.join(root, 'public', 'tutorial-essays.css')
const scanBase = path.join(root, 'src', 'docs', 'tutorial')

const stylesCss = fs.readFileSync(stylesPath, 'utf8')
const customVariant = stylesCss.match(/@custom-variant dark \([^;]+\);/)?.[0]
const themeInline = stylesCss.match(/@theme inline \{[\s\S]*?\n\}/)?.[0]
if (customVariant === undefined || themeInline === undefined) {
  throw new Error(
    'could not find @custom-variant dark / @theme inline in src/styles.css',
  )
}

const input = `@import 'tailwindcss';\n${customVariant}\n${themeInline}\n`

const tailwindDir = path.dirname(require_.resolve('tailwindcss/package.json'))
const loadStylesheet = async (id, base) => {
  const resolved =
    id === 'tailwindcss'
      ? path.join(tailwindDir, 'index.css')
      : path.resolve(base, id)
  return {
    path: resolved,
    base: path.dirname(resolved),
    content: fs.readFileSync(resolved, 'utf8'),
  }
}

const scanner = new Scanner({
  sources: [{ base: scanBase, pattern: '**/*', negated: false }],
})
const compiled = await compile(input, { base: root, loadStylesheet })
const css = compiled.build(scanner.scan())

const output = `/* GENERATED by scripts/generate-tutorial-css.mjs — do not edit.
   Tailwind utilities for the vendored tutorial essays (src/docs/tutorial).
   Linked into the StyleX and Pleat sites' index.html by vite.config.ts; the
   Tailwind site emits these classes itself. Re-run \`npm run tutorial:css\`
   when the tutorial source changes. */
${css}`

// Normalise with oxfmt (the repo formatter) so format:check and this script
// agree on the output.
const oxfmt = target =>
  execFileSync('npx', ['oxfmt', '--write', target], { cwd: root })

if (process.argv.includes('--check')) {
  const tmp = path.join(os.tmpdir(), `tutorial-css-${process.pid}.css`)
  fs.writeFileSync(tmp, output)
  oxfmt(tmp)
  const expected = fs.readFileSync(tmp, 'utf8')
  fs.rmSync(tmp, { force: true })
  const existing = fs.existsSync(outPath)
    ? fs.readFileSync(outPath, 'utf8')
    : null
  if (existing !== expected) {
    console.error(
      'public/tutorial-essays.css is stale — run `npm run tutorial:css`',
    )
    process.exit(1)
  }
} else {
  fs.writeFileSync(outPath, output)
  oxfmt(outPath)
  console.log(`wrote ${path.relative(root, outPath)}`)
}
