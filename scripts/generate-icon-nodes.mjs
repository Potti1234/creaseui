import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const sourceFiles = directory =>
  readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name)
    return entry.isDirectory()
      ? sourceFiles(path)
      : entry.name.endsWith('.ts') && entry.name !== 'icon-nodes.ts'
        ? [path]
        : []
  })
const source = sourceFiles(join(root, 'src'))
  .map(path => readFileSync(path, 'utf8'))
  .join('\n')
const catalog = JSON.parse(
  readFileSync(
    join(root, 'node_modules', 'lucide-static', 'icon-nodes.json'),
    'utf8',
  ),
)
// Keep icons referenced through named wrappers. The broad literal scan below
// can miss a literal when comments or template strings sit between quotes.
const requiredIconNames = ['code-xml']
const names = Array.from(
  new Set(
    [
      ...requiredIconNames,
      ...Array.from(source.matchAll(/['"]([^'"]+)['"]/g), match => match[1]),
    ].filter(name => catalog[name] !== undefined),
  ),
).sort()
const selectedNodes = Object.fromEntries(
  names.map(name => {
    const node = catalog[name]
    if (node === undefined) {
      throw new Error(`Unknown Lucide icon: ${name}`)
    }
    return [name, node]
  }),
)

writeFileSync(
  join(root, 'src', 'lib', 'icon-nodes.ts'),
  `// Generated by npm run icons:generate. Do not edit manually.\nexport const iconNodes = ${JSON.stringify(selectedNodes, null, 2)} as const\n`,
)

console.log(`Generated ${names.length} tree-shakable icon nodes.`)
