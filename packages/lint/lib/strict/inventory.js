/** `control`, `composition` or `null` for a tag Foldkit does not declare. */
export const tagCategory = tag =>
  CONTROL_TAGS.has(tag)
    ? 'control'
    : TAG_CONTRACTS.has(tag)
      ? 'composition'
      : null

