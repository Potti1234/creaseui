import { writeFileSync } from 'node:fs'

const { authoredPages } =
  await import('../../src/docs/components/pages/index.ts')

const clean = value => JSON.parse(JSON.stringify(value ?? null)) ?? undefined
const pages = Object.fromEntries(
  Object.values(authoredPages).map(page => [
    page.slug,
    clean({
      slug: page.slug,
      title: page.title,
      kind: page.kind,
      description: page.definition.description,
      architecture: page.definition.architecture,
      usage: page.definition.usage,
      styling: page.definition.styling,
      accessibility: page.definition.accessibility,
      keyboard: page.definition.keyboard,
      composition: page.definition.composition,
      sections: page.definition.sections,
      apiHref: page.definition.apiHref,
      apiDescription: page.definition.apiDescription,
      examples: page.definition.examples.map(example => ({
        title: example.title,
        description: example.description,
        sectionId: example.sectionId,
        heroOnly: example.heroOnly,
        keepIdsCanonical: example.keepIdsCanonical,
        previewClass: example.previewClass,
        previewLayout: example.previewLayout,
      })),
    }),
  ]),
)

writeFileSync(
  new URL('../src/docs/page-metadata.ts', import.meta.url),
  `// Generated by scripts/extract-docs-metadata.mjs. Do not edit manually.\nexport const pageMetadata = ${JSON.stringify(pages, null, 2)} as const\n`,
)
console.log(`extracted ${Object.keys(pages).length} page definitions`)
